/** Cinematic alternates used by full-bleed hero placements. */
const HERO_IMAGES = {
  'lamborghini-urus-performante': 'hero-3',
}

export const cars = raw
  .filter((car) => media.cars[car.slug]?.length)
  .map((car) => {
    const brand = brandsBySlug.get(car.brand)
    const category = categoriesBySlug.get(car.category)
    const name = `${brand.short ?? brand.name} ${car.model}`.trim()
    return {
      ...car,
      id: car.slug,
      make: brand.name,
      name,
      categoryName: category.short,
      features: featurePackFor(car.category),
      heroImage: HERO_IMAGES[car.slug] ? siteImage(HERO_IMAGES[car.slug]) : null,
      images: media.cars[car.slug].map((image, index) => ({
        src: image.src,
        alt: image.alt ? `${name} — ${image.alt}` : `${name}, photo ${index + 1}`,
        width: image.width,
        height: image.height,
        credit: image.credit,
        position: IMAGE_FOCUS[car.slug]?.[index] ?? 'center',
      })),
    }
  })

export const carsById = new Map(cars.map((car) => [car.id, car]))

export function siteImage(key) {
  const image = media.site[key]
  if (!image) return null
  return { src: image.src, alt: image.alt, width: image.width, height: image.height, credit: image.credit, position: 'center' }
}
